/*
 * Service worker-«самоликвидатор».
 *
 * Зачем он вообще нужен, если приложение service worker не использует.
 *
 * Во время настройки домена Apache какое-то время отдавал на
 * tanym.zhetysu.edu.kz ЧУЖОЙ сайт (next-cms) — из-за того, что vhost не
 * подхватился и срабатывал первый блок для этого порта. Тот сайт успел
 * зарегистрировать свой service worker, и он остался привязан к нашему
 * origin: service worker живёт в браузере сам по себе, переживает
 * Ctrl+F5 и продолжает перехватывать ВСЕ запросы в своей области.
 *
 * Отсюда брались необъяснимые ошибки: запросы к /api уходили на
 * https://tanym.zhetysu.edu.kz:4000 (и :5500), хотя ни в конфиге Apache,
 * ни в коде бэкенда никаких редиректов на эти порты нет.
 *
 * Сам по себе такой worker не исчезнет. Браузер периодически
 * перезапрашивает /sw.js, чтобы обновить его, но наш SPA-fallback отдавал
 * на этот путь index.html со статусом 200 — это не JavaScript, обновление
 * падало, и старый worker продолжал работать.
 *
 * Этот файл закрывает дыру: теперь /sw.js — валидный скрипт, который при
 * активации снимает собственную регистрацию и перезагружает открытые
 * вкладки. Пользователю ничего делать не нужно, чистка происходит сама.
 *
 * УДАЛЯТЬ НЕЛЬЗЯ, пока есть шанс встретить браузер со старой регистрацией.
 * Если приложению когда-нибудь понадобится настоящий service worker,
 * этот файл заменяется на него — лишь бы по адресу /sw.js лежал
 * корректный JS, а не HTML.
 */

self.addEventListener('install', () => {
  // Не ждём закрытия вкладок со старым worker'ом.
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Чужие кеши тоже выбрасываем — там лежат ответы с неверными портами.
      const names = await caches.keys()
      await Promise.all(names.map((name) => caches.delete(name)))

      await self.registration.unregister()

      // Перезагружаем вкладки: страница, открытая под старым worker'ом,
      // продолжит ходить через него до навигации.
      const clients = await self.clients.matchAll({ type: 'window' })
      for (const client of clients) {
        client.navigate(client.url)
      }
    })(),
  )
})
